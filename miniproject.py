num1=int(input("enter the first number : "))
num2=int(input("enter a second number : "))
print("sum of the two numbers : ",num1+num2)
print("difference of the two numbers : ",num1-num2)
print("product of the two numbers : ",num1*num2)
print(f"division of the two numbers : {num1/num2:.2f}")
print("modulus of the two numbers : ",num1%num2)
print("floor division of the two numbers : ",num1//num2)
print("exponent of the two numbers : ",num1**num2)
